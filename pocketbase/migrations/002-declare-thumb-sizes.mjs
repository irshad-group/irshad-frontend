#!/usr/bin/env node
/**
 * Declare the thumbnail sizes the portal actually asks for.
 *
 * PocketBase only generates a thumbnail for a size listed on the file field.
 * Ask for any other size and it does not error, does not warn, and does not
 * resize — it serves the original and the URL still says `?thumb=`. So a
 * directorate page rendering 21 office photographs in 112x80 boxes was
 * downloading 21 full-size photographs: 2.75 MB of images for a page that
 * needs about 60 kB of them, and nothing anywhere said so.
 *
 *   directorate_branches.photos + 224x160   the office card, at 2x
 *   directorates.photos         + 224x160   same card, same page
 *   ministries.photos           + 1200x0    the building banner
 *
 * `ministries.photos` had no sizes declared at all, so every banner request
 * fetched the original too.
 *
 * 224x160 rather than the existing 100x100 or 800x0: the card is 112x80, so
 * 100x100 is both too small and the wrong shape, and 800x0 is seven times wider
 * than the box it lands in.
 *
 * Idempotent — a size already declared is left alone. Existing thumbnails are
 * not regenerated by this; PocketBase makes each one the first time it is
 * requested and caches it from then on.
 *
 * Usage:
 *   PB_URL=... PB_EMAIL=... PB_PASSWORD=... node pocketbase/migrations/002-declare-thumb-sizes.mjs [--dry-run]
 */

const DRY = process.argv.includes('--dry-run');
const { PB_URL, PB_EMAIL, PB_PASSWORD } = process.env;
if (!PB_URL || !PB_EMAIL || !PB_PASSWORD) {
  console.error('PB_URL, PB_EMAIL and PB_PASSWORD must all be set.');
  process.exit(1);
}
const BASE = PB_URL.replace(/\/$/, '');

/** collection -> field -> sizes that must be declared on it. */
const WANTED = {
  directorate_branches: { photos: ['224x160'] },
  directorates: { photos: ['224x160'] },
  ministries: { photos: ['1200x0'] },
};

async function api(path, init = {}) {
  const res = await fetch(`${BASE}${path}`, {
    ...init,
    headers: { 'Content-Type': 'application/json', ...(init.headers || {}) },
  });
  const text = await res.text();
  if (!res.ok) throw new Error(`${init.method || 'GET'} ${path} -> ${res.status} ${text.slice(0, 300)}`);
  return text ? JSON.parse(text) : null;
}

const auth = await api('/api/collections/_superusers/auth-with-password', {
  method: 'POST',
  body: JSON.stringify({ identity: PB_EMAIL, password: PB_PASSWORD }),
});
const H = { Authorization: auth.token };

let changed = 0;
for (const [collection, fields] of Object.entries(WANTED)) {
  const col = await api(`/api/collections/${collection}`, { headers: H });
  let dirty = false;

  for (const [fieldName, sizes] of Object.entries(fields)) {
    const field = col.fields.find((f) => f.name === fieldName && f.type === 'file');
    if (!field) { console.error(`  ${collection}.${fieldName}: no such file field, skipped`); continue; }
    const have = field.thumbs ?? [];
    const missing = sizes.filter((s) => !have.includes(s));
    if (!missing.length) { console.log(`  ${collection}.${fieldName}: already declares ${sizes.join(', ')}`); continue; }
    field.thumbs = [...have, ...missing];
    dirty = true;
    changed += 1;
    console.log(`  ${collection}.${fieldName}: ${JSON.stringify(have)} -> ${JSON.stringify(field.thumbs)}`);
  }

  if (!dirty || DRY) continue;
  await api(`/api/collections/${col.id}`, {
    method: 'PATCH',
    headers: H,
    body: JSON.stringify({ fields: col.fields }),
  });
}

console.log(`\n${changed} field(s) ${DRY ? 'would gain' : 'gained'} a thumbnail size.`);
if (DRY) console.log('--dry-run: nothing written.');
